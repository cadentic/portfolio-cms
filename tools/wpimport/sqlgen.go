package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"strconv"
	"strings"
)

// writeSeed writes an idempotent SQL script that loads the snapshot into
// cms_pages, cms_media and cms_redirects (backend migration 0001).
//
// Rules:
//   - Every item is inserted as status='draft' with published_at NULL; the
//     owner publishes from the admin. first_published_at keeps the original
//     WordPress date, which also stops the publish flow from offering a
//     newsletter for imported content.
//   - Re-running refreshes only drafts nobody has touched since the import
//     (updated_at = created_at) and never changes status. Edited or published
//     items are left alone.
//   - Items whose (kind, slug) is already used by non-WordPress content are
//     skipped with a NOTICE instead of failing the whole load.
//   - Existing redirects (same from_path) are never overwritten.
func writeSeed(w io.Writer, snap *Snapshot) error {
	p := func(format string, a ...any) { fmt.Fprintf(w, format, a...) }
	p("-- Generated by tools/wpimport from %s. Do not edit; re-run the importer.\n", snap.Site)
	p("-- Load: psql \"$DATABASE_URL\" -v ON_ERROR_STOP=1 -f content/wordpress/seed.sql\n")
	p("BEGIN;\n\n")

	p("-- Pages and articles (%d), all as drafts.\n", len(snap.Items))
	for _, it := range snap.Items {
		blocks := marshal(it.Blocks)
		hero := marshal(it.Hero)
		seo := marshal(it.SEO)
		sid := strconv.FormatInt(it.SourceID, 10)
		p(`INSERT INTO cms_pages (id, kind, menu_order, slug, title, excerpt, hero, blocks,
  featured_image_url, author_name, categories, tags, seo, status, published_at,
  first_published_at, source, source_id, created_at, updated_at)
SELECT gen_random_uuid(), %s, %d, %s, %s, %s, %s::jsonb, %s::jsonb,
  %s, %s, %s::text[], %s::text[], %s::jsonb, 'draft', NULL,
  %s, 'wordpress', %s, now(), now()
WHERE NOT EXISTS (
  SELECT 1 FROM cms_pages WHERE kind = %s AND slug = %s
    AND (source IS DISTINCT FROM 'wordpress' OR source_id <> %s))
ON CONFLICT (source, source_id) WHERE source IS NOT NULL DO UPDATE SET
  kind = EXCLUDED.kind, menu_order = EXCLUDED.menu_order, slug = EXCLUDED.slug,
  title = EXCLUDED.title, excerpt = EXCLUDED.excerpt, hero = EXCLUDED.hero,
  blocks = EXCLUDED.blocks, featured_image_url = EXCLUDED.featured_image_url,
  author_name = EXCLUDED.author_name, categories = EXCLUDED.categories,
  tags = EXCLUDED.tags, seo = EXCLUDED.seo,
  first_published_at = EXCLUDED.first_published_at,
  updated_at = cms_pages.created_at
WHERE cms_pages.status = 'draft' AND cms_pages.updated_at = cms_pages.created_at;
`,
			q(it.Kind), it.MenuOrder, q(it.Slug), q(it.Title), q(it.Excerpt), q(hero), q(blocks),
			qNull(it.FeaturedImageURL), q(it.AuthorName), qArray(it.Categories), qArray(it.Tags), q(seo),
			qTime(it.OriginalPublishedAt), q(sid),
			q(it.Kind), q(it.Slug), q(sid))
	}

	p("\n-- Report items skipped because their slug is taken by other content.\n")
	var body strings.Builder
	body.WriteString("\nDECLARE missing text;\nBEGIN\n  SELECT string_agg(v.slug, ', ') INTO missing\n  FROM (VALUES\n")
	for i, it := range snap.Items {
		sep := ","
		if i == len(snap.Items)-1 {
			sep = ""
		}
		fmt.Fprintf(&body, "    (%s, %s)%s\n", q(strconv.FormatInt(it.SourceID, 10)), q(it.Slug), sep)
	}
	body.WriteString("  ) AS v(source_id, slug)\n  WHERE NOT EXISTS (SELECT 1 FROM cms_pages c WHERE c.source = 'wordpress' AND c.source_id = v.source_id);\n")
	body.WriteString("  IF missing IS NOT NULL THEN\n    RAISE NOTICE 'wordpress import skipped (slug already in use): %', missing;\n  END IF;\nEND ")
	// The body holds slugs, so close it with a dollar-quote tag that none of
	// them contains.
	tag := "$wp$"
	for i := 1; strings.Contains(body.String(), tag); i++ {
		tag = "$wp" + strconv.Itoa(i) + "$"
	}
	p("DO %s%s%s;\n", tag, body.String(), tag)

	p("\n-- Page hierarchy (only set where the item has no parent yet).\n")
	for _, it := range snap.Items {
		if it.ParentSourceID == 0 {
			continue
		}
		p("UPDATE cms_pages c SET parent_id = par.id FROM cms_pages par\n"+
			"WHERE c.source = 'wordpress' AND c.source_id = %s AND c.parent_id IS NULL\n"+
			"  AND par.source = 'wordpress' AND par.source_id = %s;\n",
			q(strconv.FormatInt(it.SourceID, 10)), q(strconv.FormatInt(it.ParentSourceID, 10)))
	}

	p("\n-- Media library (%d files under frontend/public/media/wordpress).\n", len(snap.Media))
	for _, m := range snap.Media {
		p("INSERT INTO cms_media (id, url, kind, alt, caption, width, height, source, source_id, source_url, created_at)\n"+
			"VALUES (gen_random_uuid(), %s, %s, %s, '', %s, %s, 'wordpress', %s, %s, now())\n"+
			"ON CONFLICT (source, source_id) WHERE source IS NOT NULL DO UPDATE SET\n"+
			"  url = EXCLUDED.url, width = COALESCE(cms_media.width, EXCLUDED.width), height = COALESCE(cms_media.height, EXCLUDED.height);\n",
			q(m.URL), q(m.Kind), q(m.Alt), qInt(m.Width), qInt(m.Height), q(m.File), q(m.SourceURL))
	}

	p("\n-- 301 redirects from old WordPress paths (%d).\n", len(snap.Redirects))
	for _, r := range snap.Redirects {
		p("INSERT INTO cms_redirects (id, from_path, to_path, status_code, source, created_at)\n"+
			"VALUES (gen_random_uuid(), %s, %s, %d, 'wordpress', now()) ON CONFLICT (from_path) DO NOTHING;\n",
			q(r.From), q(r.To), r.Status)
	}
	p("\nCOMMIT;\n")
	return nil
}

// q quotes a SQL string literal (standard_conforming_strings is on by default).
func q(s string) string {
	s = strings.ReplaceAll(s, "\x00", "")
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

func qNull(s string) string {
	if s == "" {
		return "NULL"
	}
	return q(s)
}

func qInt(n int) string {
	if n == 0 {
		return "NULL"
	}
	return strconv.Itoa(n)
}

func qTime(s string) string {
	if s == "" {
		return "NULL"
	}
	return q(s) + "::timestamptz"
}

// qArray renders a Postgres text[] literal, e.g. '{"Oracle","Linux"}'.
func qArray(items []string) string {
	parts := make([]string, len(items))
	for i, s := range items {
		s = strings.ReplaceAll(s, `\`, `\\`)
		s = strings.ReplaceAll(s, `"`, `\"`)
		parts[i] = `"` + s + `"`
	}
	return q("{" + strings.Join(parts, ",") + "}")
}

// marshal encodes v as compact JSON without escaping <, > and &.
func marshal(v any) string {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(v); err != nil {
		panic(err)
	}
	return strings.TrimSuffix(b.String(), "\n")
}
